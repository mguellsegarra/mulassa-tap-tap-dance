import { Soft } from './soft.js';

export function buildToonPetard() {
  const v = new Soft().ball(0, 1.1, 0, 1.08, 1.1, 1.08, '#343441', null, 24);
  v.lathe(0, 1.98, 0, [[.3, 0, '#606070'], [.32, .22, '#606070'], [.23, .28, '#8c8b94']], 1, 16);
  v.tube([[0, 2.2, 0, .1], [.12, 2.65, 0, .09], [.5, 2.83, 0, .07]], '#dfb97b', 10);
  v.ball(.53, 2.83, 0, .16, .17, .16, '#ff951d', null, 12);
  for (const [x, y, z] of [[.28, 0, 0], [-.28, .18, 0], [0, .32, 0], [.18, .24, .18]]) {
    v.tube([[.53 + x * .65, 2.83 + y * .65, z * .65, .04], [.53 + x, 2.83 + y, z, .012]], '#ffe396', 6);
  }
  return v.mesh();
}

