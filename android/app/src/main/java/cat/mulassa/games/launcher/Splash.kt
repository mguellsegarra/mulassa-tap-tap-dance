// The cold-start splash: the web cover's walking Mulassa («sense frase»), layer by layer from the web's own art and keyframes
// (SplashArt.kt, generated by tools/app/splash.mjs). The system splash shows her rest pose on the same brown at the same place
// (splash_rest, its icon); she eases from it into the walk, the cover's tile pattern fades in, and after one stride cycle the
// overlay fades out over the launcher (the catalogue and its art are read before the first frame). Still keeps the rest pose.
class SplashTrack(val dur: Float, val delay: Float, val ease: Int, val keys: Array<FloatArray>)
class SplashNode(val parent: Int, val asset: Int, val ox: Float, val oy: Float, val opacity: Float, val clip: Int, val clipBox: FloatArray?, val track: SplashTrack?)

private const val HOLD = 0.96f; private const val FADE = 0.25f
private const val BLEND_IN = 0.2f; private const val TILE_IN = 0.3f

// The CSS timing functions the keyframes use: linear, ease-in-out, ease-out, ease (per segment, as CSS applies them).
private fun eased(x: Float, ease: Int): Float {
    val c = when (ease) { 1 -> floatArrayOf(.42f, 0f, .58f, 1f); 2 -> floatArrayOf(0f, 0f, .58f, 1f); 3 -> floatArrayOf(.25f, .1f, .25f, 1f); else -> return x }
    fun b(t: Float, p1: Float, p2: Float) = 3 * (1 - t) * (1 - t) * t * p1 + 3 * (1 - t) * t * t * p2 + t * t * t
    var lo = 0f; var hi = 1f
    repeat(24) { val m = (lo + hi) / 2; if (b(m, c[0], c[2]) < x) lo = m else hi = m }
    return b((lo + hi) / 2, c[1], c[3])
}

// [tx, ty, rotation°, sx, sy, opacity] of a node `t` seconds into the walk, `w` of the way from the rest pose.
private fun values(n: SplashNode, t: Float, w: Float): FloatArray {
    val rest = floatArrayOf(0f, 0f, 0f, 1f, 1f, n.opacity)
    val tr = n.track ?: return rest
    if (w <= 0f) return rest
    val p = (((t - tr.delay) / tr.dur) % 1f).let { if (it < 0) it + 1 else it }
    val i = tr.keys.indexOfLast { it[0] <= p }.coerceAtLeast(0)
    val a = tr.keys[i]; val b = tr.keys[minOf(i + 1, tr.keys.size - 1)]
    val f = if (b[0] > a[0]) eased((p - a[0]) / (b[0] - a[0]), tr.ease) else 0f
    return FloatArray(6) { k -> val v = a[k + 1] + (b[k + 1] - a[k + 1]) * f; rest[k] + (v - rest[k]) * w }
}

@Composable
fun Splash(still: Boolean, done: () -> Unit) {
    var t by remember { mutableFloatStateOf(0f) }
    LaunchedEffect(Unit) { // seconds since her first frame: the system splash hands over on it
        val start = withFrameNanos { it }
        while (t < HOLD + FADE) t = (withFrameNanos { it } - start) / 1e9f
        done()
    }
    val tile = painterResource(R.drawable.splash_tile)
    val parts = SplashArt.nodes.map { if (it.asset != 0) painterResource(it.asset) else null }
    Canvas(
        Modifier.fillMaxSize()
            .graphicsLayer { alpha = (1f - (t - HOLD) / FADE).coerceIn(0f, 1f) }
            .background(Color(SplashArt.BACKGROUND))
            .pointerInput(Unit) { awaitPointerEventScope { while (true) awaitPointerEvent().changes.forEach { it.consume() } } }, // nothing under her takes a tap
    ) {
        // the cover's pattern, one tile per 9 s ↘ (still with reduced motion), fading in: the system splash has none
        val s = SplashArt.TILE * density
        val drift = if (still) 0f else (t / SplashArt.TILE_DRIFT % 1f) * s
        val tileAlpha = (t / TILE_IN).coerceAtMost(1f)
        var y = drift - s
        while (y < size.height) {
            var x = drift - s
            while (x < size.width) { translate(x, y) { with(tile) { draw(Size(s, s), tileAlpha) } }; x += s }
            y += s
        }
        // the figure: units → px, its centre on the screen's (as the system splash's icon)
        val k = SplashArt.SIZE * density
        val ox = size.width / 2 - SplashArt.FIG_W / 2 * k; val oy = size.height / 2 - SplashArt.FIG_H / 2 * k
        val w = if (still) 0f else (t / BLEND_IN).coerceAtMost(1f).let { it * it * (3 - 2 * it) }
        val m = ArrayList<FloatArray>(SplashArt.nodes.size); val o = FloatArray(SplashArt.nodes.size)
        SplashArt.nodes.forEachIndexed { i, n ->
            val v = values(n, t, w)
            // local = T(origin + translate) · R · S · T(-origin), as an affine [a, b, c, d, tx, ty] in units
            val r = v[2] * PI.toFloat() / 180; val cs = cos(r); val sn = sin(r)
            val a = cs * v[3]; val b = sn * v[3]; val c = -sn * v[4]; val d = cs * v[4]
            val local = floatArrayOf(a, b, c, d, n.ox + v[0] - (a * n.ox + c * n.oy), n.oy + v[1] - (b * n.ox + d * n.oy))
            val g = if (n.parent < 0) local else m[n.parent].let { p ->
                floatArrayOf(p[0] * a + p[2] * b, p[1] * a + p[3] * b, p[0] * c + p[2] * d, p[1] * c + p[3] * d,
                    p[0] * local[4] + p[2] * local[5] + p[4], p[1] * local[4] + p[3] * local[5] + p[5])
            }
            m.add(g)
            o[i] = v[5] * (if (n.parent < 0) 1f else o[n.parent])
            val painter = parts[i] ?: return@forEachIndexed
            if (o[i] <= 0f) return@forEachIndexed
            val matrix = Matrix().apply {
                this[0, 0] = g[0]; this[0, 1] = g[1]; this[1, 0] = g[2]; this[1, 1] = g[3]; this[3, 0] = ox + g[4] * k; this[3, 1] = oy + g[5] * k
            }
            withTransform({
                n.clip.takeIf { it >= 0 }?.let { SplashArt.nodes[it].clipBox }?.let { b -> // a still box (the generator checks)
                    clipRect(ox + b[0] * k, oy + b[1] * k, ox + (b[0] + b[2]) * k, oy + (b[1] + b[3]) * k)
                }
                transform(matrix)
            }) {
                translate(SplashArt.VIEW_X * k, SplashArt.VIEW_Y * k) {
                    with(painter) { draw(Size(SplashArt.VIEW_W * k, SplashArt.VIEW_H * k), o[i]) }
                }
            }
        }
    }
}
