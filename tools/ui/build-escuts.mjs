// Draws the selector pills' town arms (src/ui/escuts.js) to PNGs, one per town and screen density: public/escuts/<town>.<hash>.<px>.png,
// and the hashes to src/ui/escut-files.js (generated, never hand-edit). Run it after any change to an arm or to ESCUT_DPR:
//   node tools/ui/build-escuts.mjs [--pw=/dir/with/node_modules/playwright] [--exe=/path/to/chrome-headless-shell]
// (defaults: PLAYWRIGHT_DIR or /tmp/ui-inv-pw, and the browser that Playwright version downloaded)
// The pixels come from the same route the browser took at boot (SVG as an image, drawn to a canvas, toBlob), on a GPU-raster canvas
// as on a phone: a software canvas antialiases the edges differently (up to 100/255 on a ray's tip) and encodes a PNG twice the size.
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { TOWNS } from '../../src/game/figures.js';
import { ESCUT_DPR, escutPx, escutSvg } from '../../src/ui/escuts.js';

const OUT = new URL('../../public/escuts/', import.meta.url), FILES = new URL('../../src/ui/escut-files.js', import.meta.url);
// The arms' markup without the clip ids' counter, so the same drawing is the same hash whatever order it was asked for in.
export const escutMarkup = id => escutSvg(id).replaceAll(new RegExp(`esc-${id}-\\d+`, 'g'), `esc-${id}`);
export const escutHash = id => createHash('sha256').update(escutMarkup(id)).digest('hex').slice(0, 8);
export const escutSized = (id, px) => escutMarkup(id).replace('<svg', `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}"`);
export const escutIds = () => TOWNS.map(t => t.id).filter(id => escutSvg(id));

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const arg = k => process.argv.find(a => a.startsWith(`--${k}=`))?.slice(k.length + 3);
  const pw = arg('pw') ?? process.env.PLAYWRIGHT_DIR ?? '/tmp/ui-inv-pw';
  const { chromium } = await import(pathToFileURL(join(pw, 'node_modules/playwright/index.mjs')).href);
  const jobs = escutIds().flatMap(id => ESCUT_DPR.map(d => ({ id, px: escutPx(d), svg: escutSized(id, escutPx(d)) })));
  const gpu = ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist']; // the canvas rasters on a (software) GPU, as on a phone
  const browser = await chromium.launch({ chromiumSandbox: true, executablePath: arg('exe'), args: gpu }); // headless, the browser's sandbox on
  const page = await browser.newPage();
  const pngs = await page.evaluate(svgs => Promise.all(svgs.map(async svg => {
    const img = new Image(); img.src = `data:image/svg+xml,${encodeURIComponent(svg.svg)}`; await img.decode();
    const canvas = document.createElement('canvas'); canvas.width = canvas.height = svg.px;
    canvas.getContext('2d').drawImage(img, 0, 0, svg.px, svg.px);
    const blob = await new Promise(done => canvas.toBlob(done)), reader = new FileReader();
    return new Promise(done => { reader.onload = () => done(reader.result.split(',')[1]); reader.readAsDataURL(blob); });
  })), jobs.map(({ svg, px }) => ({ svg, px })));
  await browser.close();
  mkdirSync(OUT, { recursive: true });
  const name = j => `${j.id}.${escutHash(j.id)}.${j.px}.png`, keep = new Set(jobs.map(name));
  jobs.forEach((j, i) => writeFileSync(new URL(name(j), OUT), Buffer.from(pngs[i], 'base64')));
  for (const f of readdirSync(OUT)) if (!keep.has(f)) rmSync(new URL(f, OUT)); // a drawing that changed leaves its old files behind
  writeFileSync(FILES, `// GENERATED by tools/ui/build-escuts.mjs (never hand-edit): the hash of each town's arms, in the names of public/escuts/*.png.\n`
    + `export const ESCUT_HASH = {\n${escutIds().map(id => `  '${id}': '${escutHash(id)}',`).join('\n')}\n};\n`);
  console.log(`${keep.size} PNGs in public/escuts/, ${escutIds().length} towns`);
}
