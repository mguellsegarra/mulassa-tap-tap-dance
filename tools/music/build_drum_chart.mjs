// Rolls where the touch game holds a long note; the same on every level.
const ROLLS = [[32, 34], [64, 67], [96, 98], [128, 131], [136, 139]];
// The song's two drumrolls (song.balloonBeats), with the hits to pop them per level (the touch game's rate: 1.7, 2.7, 4 a beat).
const BALLOONS = [[140, 143, [5, 8, 12]], [224, 228, [7, 11, 16]]];
const LAST = [228, 'D']; // the final hit, on the song's last beat

export function buildDrumChart() {
  const levels = [[], [], []];
  for (const row of BARS.trim().split('\n')) {
    const [bar, ...cols] = row.trim().split(/\s+/);
    if (cols.length !== 3 || cols.some(c => !/^[dkDK.]{16}$/.test(c))) throw new Error(`bar ${bar}: three columns of sixteen d k D K .`);
    cols.forEach((c, L) => [...c].forEach((ch, i) => { if (ch !== '.') levels[L].push([Number(bar) + i / 4, ch]); }));
  }
  levels.forEach((ev, L) => {
    for (const [a, b] of ROLLS) ev.push([a, 'r', b]);
    for (const [a, b, need] of BALLOONS) ev.push([a, 'b', b, need[L]]);
    ev.push(LAST);
    ev.sort((x, y) => x[0] - y[0]);
  });
  return { version: 1, levels };
}
export const renderDrumChart = chart => `{ "version": ${chart.version}, "levels": [\n${chart.levels.map(l => JSON.stringify(l)).join(',\n')}\n] }\n`;

// d/k/D/K/r/b counts, the rim's share of the notes and the notes in the busiest and quietest 7 s, per level.
export function drumChartStats(chart, beats) {
  return chart.levels.map(ev => {
    const n = { d: 0, k: 0, D: 0, K: 0, r: 0, b: 0 };
    for (const e of ev) n[e[1]]++;
    const t = ev.filter(e => 'dkDK'.includes(e[1])).map(e => timeAtBeat(beats, e[0])), per7 = [];
    for (let a = t[0]; a + 7 <= t.at(-1); a += 0.5) per7.push(t.filter(x => x >= a && x < a + 7).length);
    return { ...n, notes: t.length, ka: (n.k + n.K) / t.length, mean7: t.length / (t.at(-1) - t[0]) * 7, min7: Math.min(...per7), max7: Math.max(...per7) };
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const chart = buildDrumChart(), song = JSON.parse(readFileSync(new URL('../../src/song-mulassa.json', import.meta.url)));
  writeFileSync(OUT, renderDrumChart(chart));
  drumChartStats(chart, song.beats).forEach((s, L) => console.log(`${['FÀCIL', 'NORMAL', 'DIFÍCIL'][L].padEnd(8)}d ${s.d}  k ${s.k}  D ${s.D}  K ${s.K}  r ${s.r}  b ${s.b}  notes ${s.notes}  ka ${(s.ka * 100).toFixed(1)}%  per 7 s: mean ${s.mean7.toFixed(1)}, ${s.min7}-${s.max7}`));
}
