// Mulassa Pop's second tune, the Ball del Drac: its melody as mulassa.cat's Drac plays it (the music form, compiled by the one
// compiler, src/music-form) and its harmony by build_drac.py's rule (V_BARS read from that file: one source), from the pickup to
// the last note held for 4 beats, written to src/jocs/games/pop/melody-drac.js. Pop plays it on its own tempo (conductor.js),
// never the Drac's. Run after the Drac's form or harmony changes; then node tools/jocs/pop-sim.mjs. Usage: node tools/jocs/pop-drac.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const root = new URL('../../', import.meta.url);
const tl = JSON.parse(execFileSync('node', [new URL('tools/music/compile-music-form.mjs', root).pathname, 'drac'], { encoding: 'utf8' }));
const py = readFileSync(new URL('tools/music/build_drac.py', root), 'utf8');
const V_BARS = new Set(py.match(/^V_BARS = \{([\d, ]+)\}/m)[1].split(',').map(Number));
const PASSING_IV = [19, 52]; // build_drac.py: «C F E: the F is a passing IV», half the bar on C

const pick = tl.occurrences[0], body = tl.occurrences.slice(1);
const FROM = pick.start, LAST = tl.melody.at(-1)[0], TO = LAST + 4;
const r = x => Math.round(x * 1e6) / 1e6; // the compiler's triplets as floats: 6 places keep them exact enough, and short
const melody = tl.melody.map(([b, d, m]) => [r(b), r(Math.min(d, TO - b)), m]);
const chords = [[FROM, body[0].start, 'G']];
for (const { bar, start, dur } of body) {
  if (start >= TO) break;
  if (PASSING_IV.includes(bar)) chords.push([start, start + dur / 2, 'G'], [start + dur / 2, start + dur, 'C']);
  else chords.push([start, start + dur, V_BARS.has(bar) ? 'D' : 'G']);
}
chords.push([chords.at(-1)[1], TO, 'G']);
const merged = chords.reduce((a, c) => (a.length && a.at(-1)[2] === c[2] && a.at(-1)[1] === c[0] ? (a.at(-1)[1] = Math.min(c[1], TO), a) : [...a, [c[0], Math.min(c[1], TO), c[2]]]), []);

const out = `// Generated by tools/jocs/pop-drac.mjs from music/drac (the form) and tools/music/build_drac.py (the harmony): do not edit.
// The Ball del Drac de Valls (Francesc Bofarull), G major, in its own beats from its pickup: melody [beat, beats, midi],
// chords [from, to, name]. melody.js places it after the Mulassa's tune.
export const DRAC = { from: ${FROM}, to: ${TO}, melody: ${JSON.stringify(melody)}, chords: ${JSON.stringify(merged)} };
`;
writeFileSync(new URL('src/jocs/games/pop/melody-drac.js', root), out);
console.log(`melody-drac.js: ${melody.length} notes, ${merged.length} chords, beats ${FROM}–${TO}`);
